// Regenerates open-sse/providers/bedrockPricing.js from models.dev's
// amazon-bedrock catalog. Keys are kept exactly as Bedrock spells them because
// the price depends on the geo prefix: regional cross-region profiles (us.,
// eu., jp., au., apac.) list ~10% above the bare on-demand id, "global." does not.
//
//   node .claude/skills/bedrock-pricing/sync-bedrock-pricing.mjs   (run via the bedrock-pricing skill)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CATALOG_URL = "https://models.dev/api.json";
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../open-sse/providers/bedrockPricing.js");

const res = await fetch(CATALOG_URL, { signal: AbortSignal.timeout(30000) });
if (!res.ok) throw new Error(`models.dev ${res.status}`);
const models = (await res.json())["amazon-bedrock"]?.models || {};

const rows = Object.entries(models)
  .filter(([, m]) => m?.cost && typeof m.cost.input === "number" && typeof m.cost.output === "number")
  .map(([id, m]) => {
    const p = { input: m.cost.input, output: m.cost.output };
    if (typeof m.cost.cache_read === "number") p.cached = m.cost.cache_read;
    if (typeof m.cost.cache_write === "number") p.cache_creation = m.cost.cache_write;
    return [id, p];
  })
  .sort(([a], [b]) => a.localeCompare(b));

const lines = rows.map(([id, p]) => `  ${JSON.stringify(id)}: ${JSON.stringify(p).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ")},`);
const out = `// GENERATED by the bedrock-pricing skill (.claude/skills/bedrock-pricing) from ${CATALOG_URL} — do not hand-edit.
// USD per 1M tokens; cached = cache read, cache_creation = cache write.
// Keys are exact Bedrock ids: a regional profile ("us.", "eu.", ...) is priced
// above its bare id, "global." matches the bare id. Context tiers above 200k
// (OpenAI-on-Bedrock) are not modeled — the base tier is used.
// Synced: ${new Date().toISOString().slice(0, 10)} (${rows.length} models)
export const BEDROCK_PRICING = {
${lines.join("\n")}
};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${rows.length} models to ${path.relative(process.cwd(), OUT)}`);
